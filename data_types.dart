void main() {
  // Data Types

  // Numbers, Strings, Booleans, Lists, Maps, Dynamic

  // Strings
  String name = 'Nenye';
  print("String: $name");

  // Integers

  int myAge = 222;
  print(myAge);
  // Doubles
  double amount = 100.3;
  print(amount);

  // Booleans
  bool test = true;
  bool num = 2 > 8;
  print('$test and $num');

  // Dynamic
  dynamic his_name = "Vanilla";
  print(his_name);
}
